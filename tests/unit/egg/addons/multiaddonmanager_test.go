const mamCfg = `// MultiAddonManager settings
mm_extra_addons "3070923343,3121403432" // UI and sounds
mm_client_extra_addons	3090221423
mm_extra_addons_timeout "15"
mm_addon_connection_timeout 45
mm_addon_mount_download "1"
mm_cache_clients_with_addons 1
mm_cache_clients_duration "600"
mm_block_disconnect_messages 0
mm_unknown_setting 1
sv_cheats 1
`

func TestParseMultiAddonManagerConfigMapsEverySetting(t *testing.T) {
	got := addons.ParseMultiAddonManagerConfig([]byte(mamCfg))
	want := map[string]any{
		"addons_extra":                     "3070923343,3121403432",
		"addons_client_extra":              "3090221423",
		"addons_extra_timeout":             15.0,
		"addons_connection_timeout":        45.0,
		"addons_mount_download":            true,
		"addons_cache_clients":             true,
		"addons_cache_duration":            600.0,
		"addons_block_disconnect_messages": false,
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("parsed %#v", got)
	}
}

func TestParseMultiAddonManagerConfigSkipsCommentsAndBadValues(t *testing.T) {
	got := addons.ParseMultiAddonManagerConfig([]byte("// mm_extra_addons 1\nmm_extra_addons_timeout soon\nmm_extra_addons \"\"; mm_client_extra_addons 5\n"))
	if want := map[string]any{"addons_extra": ""}; !reflect.DeepEqual(got, want) {
		t.Fatalf("parsed %#v", got)
	}
}

// mamServer lays out a server volume with an egg-installed MultiAddonManager.
func mamServer(t *testing.T, cfg string) *addons.Env {
	t.Helper()
	e := nativeEnv(t)
	game := filepath.Join(e.Root, "game", "csgo")
	nativeWrite(t, game, "addons/metamod/multiaddonmanager.vdf", "\"Metamod Plugin\"\n{\n\"file\" \"addons/multiaddonmanager/bin/multiaddonmanager\"\n}\n")
	nativeWrite(t, game, "addons/multiaddonmanager/bin/multiaddonmanager.so", "binary")
	nativeWrite(t, e.Root, "egg/native-addons/multiaddonmanager.json", "{}")
	if cfg != "" {
		nativeWrite(t, game, "cfg/multiaddonmanager/multiaddonmanager.cfg", cfg)
	}
	return e
}

func mamGone(t *testing.T, e *addons.Env) {
	t.Helper()
	game := filepath.Join(e.Root, "game", "csgo")
	for _, p := range []string{filepath.Join(game, "addons/metamod/multiaddonmanager.vdf"), filepath.Join(game, "addons/multiaddonmanager/bin"), filepath.Join(e.Root, "egg/native-addons/multiaddonmanager.json")} {
		if _, err := os.Lstat(p); !os.IsNotExist(err) {
			t.Fatalf("%s still present (%v)", p, err)
		}
	}
	if addons.MultiAddonManagerInstalled(e.Root) {
		t.Fatal("MultiAddonManager still reported installed")
	}
}

func TestRetireMultiAddonManagerMovesSettingsAndUnloadsIt(t *testing.T) {
	e := mamServer(t, mamCfg)
	if !addons.MultiAddonManagerInstalled(e.Root) {
		t.Fatal("fixture not detected")
	}
	if err := e.RetireMultiAddonManager(); err != nil {
		t.Fatal(err)
	}
	mamGone(t, e)
	game := filepath.Join(e.Root, "game", "csgo")
	if got := nativeRead(t, game, "cfg/multiaddonmanager/multiaddonmanager.cfg"); got != mamCfg {
		t.Fatal("MultiAddonManager's own config must be left for reference")
	}
	var moved map[string]any
	if err := json.Unmarshal([]byte(nativeRead(t, game, addons.AddonManagerConfig)), &moved); err != nil {
		t.Fatal(err)
	}
	if moved["addons_extra"] != "3070923343,3121403432" || moved["addons_client_extra"] != "3090221423" || moved["addons_cache_clients"] != true || moved["addons_extra_timeout"] != 15.0 {
		t.Fatalf("moved settings %#v", moved)
	}
	// A second boot has nothing left to do.
	if err := e.RetireMultiAddonManager(); err != nil {
		t.Fatal(err)
	}
}

func TestRetireMultiAddonManagerKeepsAnExistingAddonManagerConfig(t *testing.T) {
	e := mamServer(t, mamCfg)
	game := filepath.Join(e.Root, "game", "csgo")
	nativeWrite(t, game, addons.AddonManagerConfig, `{"addons_extra": "1"}`)
	if err := e.RetireMultiAddonManager(); err != nil {
		t.Fatal(err)
	}
	mamGone(t, e)
	if got := nativeRead(t, game, addons.AddonManagerConfig); got != `{"addons_extra": "1"}` {
		t.Fatalf("operator config overwritten: %s", got)
	}
}

// S2Script releases ship each bundled plugin's default config (generated by
// `s2s config gen`; testdata is that output for addonmanager), so it is
// usually on disk before MultiAddonManager is retired.
func TestRetireMultiAddonManagerFillsTheShippedDefaultConfig(t *testing.T) {
	shipped, err := os.ReadFile(filepath.Join("testdata", "addonmanager-default.jsonc"))
	if err != nil {
		t.Fatal(err)
	}
	e := mamServer(t, mamCfg)
	game := filepath.Join(e.Root, "game", "csgo")
	nativeWrite(t, game, addons.AddonManagerConfig, string(shipped))
	if err := e.RetireMultiAddonManager(); err != nil {
		t.Fatal(err)
	}
	mamGone(t, e)
	got := nativeRead(t, game, addons.AddonManagerConfig)
	for _, want := range []string{
		`"addons_extra": "3070923343,3121403432"`,
		`"addons_client_extra": "3090221423"`,
		`"addons_extra_timeout": 15,`,
		`"addons_connection_timeout": 45,`,
		`"addons_mount_download": true`,
		`"addons_cache_clients": true,`,
		`"addons_cache_duration": 600,`,
		`"addons_block_disconnect_messages": false,`,
		"// string — Workshop addons to download",
	} {
		if !strings.Contains(got, want) {
			t.Fatalf("merged config misses %q:\n%s", want, got)
		}
	}
	if strings.Count(got, "\n") != strings.Count(string(shipped), "\n") {
		t.Fatalf("merge changed the file's shape:\n%s", got)
	}
}

func TestRetireMultiAddonManagerWithoutAddonsLeavesDefaultsToS2Script(t *testing.T) {
	for _, cfg := range []string{"", "mm_extra_addons \"\"\nmm_cache_clients_with_addons 1\n"} {
		e := mamServer(t, cfg)
		if err := e.RetireMultiAddonManager(); err != nil {
			t.Fatal(err)
		}
		mamGone(t, e)
		if _, err := os.Stat(filepath.Join(e.Root, "game", "csgo", addons.AddonManagerConfig)); !os.IsNotExist(err) {
			t.Fatalf("config written with no addons to move (%v)", err)
		}
	}
}

func TestRetireMultiAddonManagerIgnoresServersWithoutIt(t *testing.T) {
	e := nativeEnv(t)
	if err := e.RetireMultiAddonManager(); err != nil {
		t.Fatal(err)
	}
	nativeWrite(t, filepath.Join(e.Root, "game", "csgo"), "cfg/multiaddonmanager/multiaddonmanager.cfg", mamCfg)
	if err := e.RetireMultiAddonManager(); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(e.Root, "game", "csgo", addons.AddonManagerConfig)); !os.IsNotExist(err) {
		t.Fatal("settings moved for a server that no longer loads MultiAddonManager")
	}
}

func TestAddonManagerActiveNeedsTheEnabledPackage(t *testing.T) {
	e := nativeEnv(t)
	game := filepath.Join(e.Root, "game", "csgo")
	nativeWrite(t, game, "addons/s2script/plugins/disabled/_s2script_addonmanager.s2sp", "zip")
	if addons.AddonManagerActive(e.Root) {
		t.Fatal("a disabled addonmanager cannot replace MultiAddonManager")
	}
	nativeWrite(t, game, "addons/s2script/plugins/_s2script_addonmanager.s2sp", "zip")
	if addons.AddonManagerActive(e.Root) {
		t.Fatal("addonmanager cannot run while Metamod does not load S2Script")
	}
	nativeWrite(t, game, "addons/metamod/s2script.vdf", "loader")
	if !addons.AddonManagerActive(e.Root) {
		t.Fatal("enabled addonmanager not detected")
	}
}
