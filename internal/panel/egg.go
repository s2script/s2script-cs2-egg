type Variable struct {
	Name         string `json:"name"`
	Description  string `json:"description"`
	EnvVariable  string `json:"env_variable"`
	DefaultValue string `json:"default_value"`
	UserViewable bool   `json:"user_viewable"`
	UserEditable bool   `json:"user_editable"`
	Rules        string `json:"rules"`
	FieldType    string `json:"field_type"`
}

// Generate emits a deterministic PTDL_v2 document for a locally built image.
func Generate(image string) ([]byte, error) {
	if strings.TrimSpace(image) == "" || strings.ContainsAny(image, "\x00\r\n\t ") {
		return nil, errors.New("image must be a nonempty container image reference")
	}
	vars := []Variable{}
	add := func(name, env, value, rules, description string) {
		vars = append(vars, Variable{name, description, env, value, true, true, rules, "text"})
	}
	add("Steam app ID", "SRCDS_APPID", "730", "required|integer|in:730", "CS2 app ID; only 730 is supported.")
	add("Server identity", "SERVER_ID", "", "nullable|string|max:128", "Optional stable operator identity; no fleet identity is invented.")
	add("Startup map", "SRCDS_MAP", "de_dust2", "required|string|max:256", "CS2 startup map.")
	add("Maximum players", "SRCDS_MAXPLAYERS", "32", "required|integer|min:1|max:64", "Maximum player slots.")
	add("Game type", "GAME_TYPE", "0", "required|integer|min:0", "CS2 game_type value.")
	add("Game mode", "GAME_MODE", "0", "required|integer|min:0", "CS2 game_mode value.")
	add("Steam login token", "STEAM_ACC", "", "nullable|string|max:256", "Secret GSLT; required unless tokenless mode is explicitly enabled.")
	add("Allow tokenless", "ALLOW_TOKENLESS", "0", "required|boolean", "Explicitly permit a server without a GSLT.")
	add("Skip game update", "SRCDS_STOP_UPDATE", "0", "required|boolean", "skip startup game updates.")
	add("Validate game files", "SRCDS_VALIDATE", "0", "required|boolean", "validate CS2 files with SteamCMD.")
	add("Additional parameters", "CUSTOM_PARAMS", "", "nullable|string|max:4096", "Quoted argument data; never executed through a shell.")
	add("Update S2Script", "S2SCRIPT_UPDATE", "1", "required|boolean", "update the matched S2Script release on startup.")
	add("Update Metamod", "METAMOD_UPDATE", "1", "required|boolean", "update compatible Metamod on startup.")
	add("S2Script channel", "S2SCRIPT_CHANNEL", "stable", "required|string|in:stable,prerelease", "Startup release selection channel.")
	add("S2Script version", "S2SCRIPT_VERSION", "latest", "required|string|max:128", "Latest or an exact S2Script version pin.")
	add("Metamod version", "METAMOD_VERSION", "latest", "required|string|max:128", "Latest or an exact Metamod version pin.")
	add("Installed plugin list", "S2SCRIPT_PLUGIN_FILE", "s2script-plugins.json", "required|string|max:256", "Installed-plugin inventory path, relative within server root.")
	add("Native HUD support", "S2SCRIPT_HUD", "0", "required|boolean", "Optional MultiAddonManager HUD support.")
	add("Debug TCP port", "GDB_DEBUG_PORT", "0", "required|integer|min:0|max:65535", "0 disables; otherwise requires debug image, a distinct allocated TCP port and restricted admin access.")
	add("Discord webhook", "DISCORD_WEBHOOK_URL", "", "nullable|url|max:512", "Optional secret HTTPS Discord webhook URL; standalone lifecycle delivery; configure privately.")
	for _, p := range catalog.Bundled() {
		state := "disabled"
		if p.DefaultEnabled {
			state = "enabled"
		}
		add(strings.TrimPrefix(p.Name, "@s2script/"), p.Variable, "default", "required|string|in:default,0,1", "default inherits installed-list policy then release default ("+state+"); 0 disables, 1 enables. Every installed entry is checked on startup.")
	}
	egg := map[string]any{
		"_comment":    "Generated by cmd/egggen. Build the local runtime image before provisioning.",
		"meta":        map[string]string{"version": "PTDL_v2", "update_url": ""},
		"exported_at": "2026-10-11T00:00:00+00:00",
		"name":        "S2Script CS2 (standalone)", "author": "noreply@example.com",
		"description": "CS2 with Metamod and S2Script. First start installs app 730, checks all installed plugins, and supervises readiness/lifecycle notifications.",
		"features":    []string{}, "docker_images": map[string]string{"Local runtime build": image}, "file_denylist": []string{},
		"startup":   "s2egg run",
		"config":    map[string]any{"files": "{}", "startup": "{\"done\":\"S2EGG_READY\"}", "logs": "{}", "stop": "quit"},
		"scripts":   map[string]any{"installation": map[string]string{"script": "#!/bin/sh\nset -eu\nprintf '%s\\n' 'First start installs CS2 app 730 and the selected Metamod/S2Script stack in the persistent server root. Build the configured image on the node before starting.'\n", "container": image, "entrypoint": "sh"}},
		"variables": vars,
	}
	b, err := json.MarshalIndent(egg, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(b, '\n'), nil
}

// CatalogMarkdown documents the same reviewed catalog used by Generate.
func CatalogMarkdown() []byte {
	var out strings.Builder
	out.WriteString("# Bundled plugin controls\n\nGenerated by cmd/egggen from internal/catalog. Runtime checks all installed entries at startup.\n\nAll controls default to `default`: inherit an installed-list override when present, then the release default. `0` forces disabled and `1` forces enabled. Disabled plugins will remain tracked for updates.\n\n| Plugin | Environment variable | Release default |\n| --- | --- | --- |\n")
	for _, p := range catalog.Bundled() {
		state := "disabled"
		if p.DefaultEnabled {
			state = "enabled"
		}
		fmt.Fprintf(&out, "| `%s` | `%s` | %s |\n", p.Name, p.Variable, state)
	}
	return []byte(out.String())
}
